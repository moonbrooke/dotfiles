local utils = require("_utils")
local gaps_enabled = require("_gap")
local is_animation = require("_animation_toggle")
local saved_layout = require("_layout_state").get()

--- Read gap value from $HOME/.cache, falling back to default
--- @param name string cache filename (eg "hypr_gaps_in")
--- @param default integer fallback value
--- @return integer
local function cached_gap(name, default)
    local f = io.open(utils.cache_path(name), "r")
    if f then
        local v = tonumber(f:read("*l"))
        f:close()
        if v ~= nil and v >= 0 and math.floor(v) == v then
            return v
        end
    end
    return default
end

local gaps_in_value = cached_gap("hypr_gaps_in", 5)
local gaps_out_value = cached_gap("hypr_gaps_out", 10)

--- Read the palette generated by ~/scripts/theme, falling back to Tokyo Night.
--- @return table
local function load_theme()
    local ok, colors = pcall(dofile, utils.cache_path("theme_colors.lua"))
    if ok and type(colors) == "table" then
        return {
            border_active_1 = colors.border_active_1 or "9aa5ce",
            border_active_2 = colors.border_active_2 or "565f89",
            border_inactive = colors.border_inactive or "24283b",
            fg = colors.fg or "c0caf5",
        }
    end
    return {
        border_active_1 = "9aa5ce",
        border_active_2 = "565f89",
        border_inactive = "24283b",
        fg = "c0caf5",
    }
end

local theme = load_theme()

hl.config({
    general = {
        gaps_in = gaps_enabled and gaps_in_value or 0,
        gaps_out = gaps_enabled and gaps_out_value or 0,
        border_size = 3,
        resize_on_border = false,
        allow_tearing = false,
        layout = saved_layout,

        col = {
            active_border = {
                colors = {
                    "rgb(" .. theme.border_active_1 .. ")",
                    "rgb(" .. theme.border_active_2 .. ")",
                },
                angle = 45,
            },
            inactive_border = "rgb(" .. theme.border_inactive .. ")",
        },
    },

    decoration = {
        rounding = 0,
        rounding_power = 2,

        active_opacity = 0.95,
        inactive_opacity = 0.95,

        shadow = {
            enabled = false,
            range = 0,
            render_power = 2,
            offset = { 8, 8 },
            color = "rgb(" .. theme.fg .. ")",
            color_inactive = "rgba(" .. theme.fg .. "00)",
        },

        blur = {
            enabled = false,
            size = 5,
            passes = 1,
            vibrancy = 0.1696,
        },
    },

    animations = {
        enabled = is_animation,
    },
})
